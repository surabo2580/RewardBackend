-- 1) reward_sponsors: add sponsor_type used by new code
ALTER TABLE reward_sponsors
ADD COLUMN IF NOT EXISTS sponsor_type VARCHAR(32);

UPDATE reward_sponsors
SET sponsor_type = 'CHILD'
WHERE sponsor_type IS NULL OR sponsor_type = '';

UPDATE reward_sponsors
SET sponsor_type = 'HOST'
WHERE sponsor_type = 'CHILD' AND sponsor_code LIKE 'HOST_%';

ALTER TABLE reward_sponsors
ALTER COLUMN sponsor_type SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'chk_reward_sponsors_type'
  ) THEN
    ALTER TABLE reward_sponsors
    ADD CONSTRAINT chk_reward_sponsors_type
    CHECK (sponsor_type IN ('HOST','CHILD','PARTNER'));
  END IF;
END $$;

