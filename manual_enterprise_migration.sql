-- 3) reward_branches: switch from global code unique to tenant-scoped unique
DO $$
DECLARE c RECORD;
BEGIN
  FOR c IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'reward_branches'::regclass
      AND contype = 'u'
      AND conname <> 'uk_reward_branches_tenant_code'
  LOOP
    BEGIN
      EXECUTE 'ALTER TABLE reward_branches DROP CONSTRAINT ' || quote_ident(c.conname);
    EXCEPTION WHEN others THEN
      NULL;
    END;
  END LOOP;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'uk_reward_branches_tenant_code'
  ) THEN
    ALTER TABLE reward_branches
    ADD CONSTRAINT uk_reward_branches_tenant_code
    UNIQUE (tenant_id, code);
  END IF;
END $$;

